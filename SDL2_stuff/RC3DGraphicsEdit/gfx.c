uint32_t darken(uint32_t c, float f)
{
    uint8_t r = (c >> 16) & 0xFF;
    uint8_t g = (c >> 8)  & 0xFF;
    uint8_t b = (c >> 0)  & 0xFF;

    r = (uint8_t)(r * f);
    g = (uint8_t)(g * f);
    b = (uint8_t)(b * f);

    return (0xFFu << 24) | ((uint32_t)r << 16) | ((uint32_t)g << 8) | b;
}

void drawRectL(int x, int y, int w, int h, uint8_t col){
    int x0 = x;
    int y0 = y;
    int x1 = x + w - 1;
    int y1 = y + h - 1;
    drawLine(x0, y0, x0, y1, col);  // left
    drawLine(x0, y0, x1, y0, col);  // top
    drawLine(x1, y0, x1, y1, col);  // right
    drawLine(x0, y1, x1, y1, col);  // bottom
}

void drawRect(int x, int y, int w, int h, uint8_t col)
{
    if (w <= 0 || h <= 0) return;

    int x0 = x;
    int y0 = y;
    int x1 = x + w - 1;
    int y1 = y + h - 1;

    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 >= SCREEN_W) x1 = SCREEN_W - 1;
    if (y1 >= SCREEN_H) y1 = SCREEN_H - 1;

    if (x0 > x1 || y0 > y1) return;

    const int fillW = (x1 - x0) + 1;

    for (int yy = y0; yy <= y1; yy++) {
        memset(&fb[(yy * SCREEN_W) + x0], col, fillW);
    }
}

void drawChar(int x, int y, char c, uint8_t color)
{
    const uint8_t *glyph;
    int row;

    if (x >= SCREEN_W || y >= SCREEN_H) return;
    if (x <= -8 || y <= -16) return;

    glyph = font[(uint8_t)c];

    for (row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        int py0, py1;

        if (!bits) continue;

        py0 = y + (row * 2);
        py1 = py0 + 1;

        if ((unsigned)py0 < SCREEN_H) {
            if (x >= 0 && x <= (SCREEN_W - 8)) {
                uint8_t *dst = &fb[(py0 * SCREEN_W) + x];

                if (bits & 0x80) dst[0] = color;
                if (bits & 0x40) dst[1] = color;
                if (bits & 0x20) dst[2] = color;
                if (bits & 0x10) dst[3] = color;
                if (bits & 0x08) dst[4] = color;
                if (bits & 0x04) dst[5] = color;
                if (bits & 0x02) dst[6] = color;
                if (bits & 0x01) dst[7] = color;
            } else {
                uint8_t *dst = &fb[(py0 * SCREEN_W)];

                if ((bits & 0x80) && (unsigned)(x + 0) < SCREEN_W) dst[x + 0] = color;
                if ((bits & 0x40) && (unsigned)(x + 1) < SCREEN_W) dst[x + 1] = color;
                if ((bits & 0x20) && (unsigned)(x + 2) < SCREEN_W) dst[x + 2] = color;
                if ((bits & 0x10) && (unsigned)(x + 3) < SCREEN_W) dst[x + 3] = color;
                if ((bits & 0x08) && (unsigned)(x + 4) < SCREEN_W) dst[x + 4] = color;
                if ((bits & 0x04) && (unsigned)(x + 5) < SCREEN_W) dst[x + 5] = color;
                if ((bits & 0x02) && (unsigned)(x + 6) < SCREEN_W) dst[x + 6] = color;
                if ((bits & 0x01) && (unsigned)(x + 7) < SCREEN_W) dst[x + 7] = color;
            }
        }

        if ((unsigned)py1 < SCREEN_H) {
            if (x >= 0 && x <= (SCREEN_W - 8)) {
                uint8_t *dst = &fb[(py1 * SCREEN_W) + x];

                if (bits & 0x80) dst[0] = color;
                if (bits & 0x40) dst[1] = color;
                if (bits & 0x20) dst[2] = color;
                if (bits & 0x10) dst[3] = color;
                if (bits & 0x08) dst[4] = color;
                if (bits & 0x04) dst[5] = color;
                if (bits & 0x02) dst[6] = color;
                if (bits & 0x01) dst[7] = color;
            } else {
                uint8_t *dst = &fb[(py1 * SCREEN_W)];

                if ((bits & 0x80) && (unsigned)(x + 0) < SCREEN_W) dst[x + 0] = color;
                if ((bits & 0x40) && (unsigned)(x + 1) < SCREEN_W) dst[x + 1] = color;
                if ((bits & 0x20) && (unsigned)(x + 2) < SCREEN_W) dst[x + 2] = color;
                if ((bits & 0x10) && (unsigned)(x + 3) < SCREEN_W) dst[x + 3] = color;
                if ((bits & 0x08) && (unsigned)(x + 4) < SCREEN_W) dst[x + 4] = color;
                if ((bits & 0x04) && (unsigned)(x + 5) < SCREEN_W) dst[x + 5] = color;
                if ((bits & 0x02) && (unsigned)(x + 6) < SCREEN_W) dst[x + 6] = color;
                if ((bits & 0x01) && (unsigned)(x + 7) < SCREEN_W) dst[x + 7] = color;
            }
        }
    }
}

void drawText(int x, int y, const char *text, uint8_t color)
{
    int cx = x;
    int cy = y;

    while (*text) {
        if (*text == '\n') {
            cx = x;
            cy += 8;
        } else {
            drawChar(cx, cy, *text, color);
            cx += 8;
        }
        text++;
    }
}

static uint32_t ppb_be32(uint32_t v)
{
    return ((v & 0x000000FFu) << 24) |
           ((v & 0x0000FF00u) <<  8) |
           ((v & 0x00FF0000u) >>  8) |
           ((v & 0xFF000000u) >> 24);
}

static uint16_t ppb_be16(uint16_t v)
{
    return (uint16_t)(((v & 0x00FFu) << 8) |
                      ((v & 0xFF00u) >> 8));
}

int LoadPPB(const char *filename, uint8_t *img, int destWidth, int destHeight){
    // [0] configbits
    // [1..2] width  (big-endian)
    // [3..4] height (big-endian)
    // [5..8] payload length (big-endian)
    // [9..15] reserved = 0
    // colour palette info
    // [16 + 1024]  // 1024 bytes of palette info
    // [1040 ... n] // the 8bit pixel data

    ppb_t head;
    FILE *fp = NULL;
    uint32_t payloadLen;
    uint16_t srcWidth;
    uint16_t srcHeight;
    size_t srcSize;
    size_t destSize;
    uint8_t *src = NULL;
    int ok = 0;

    if (!img || destWidth <= 0 || destHeight <= 0) {
        return 0;
    }

    destSize = (size_t)destWidth * (size_t)destHeight;
    memset(img, 0, destSize);

    fp = fopen(filename, "rb");
    if (!fp) {
        return 0;
    }

    if (fread(&head, 1, sizeof(head), fp) != sizeof(head)) {
        goto cleanup;
    }

    srcWidth = ppb_be16(head.width_be);
    srcHeight = ppb_be16(head.height_be);
    payloadLen = ppb_be32(head.length_be);

    if (srcWidth == 0 || srcHeight == 0 || payloadLen == 0) {
        goto cleanup;
    }

    srcSize = (size_t)srcWidth * (size_t)srcHeight;

    /* Reject malformed or absurdly large payloads before allocating or reading. */
    if (srcSize != (size_t)payloadLen || srcSize > (32u * 1024u * 1024u)) {
        goto cleanup;
    }

    src = malloc(srcSize);
    if (!src) {
        goto cleanup;
    }

    if (fread(src, 1, srcSize, fp) != srcSize) {
        goto cleanup;
    }

    if ((int)srcWidth == destWidth && (int)srcHeight == destHeight) {
        memcpy(img, src, destSize);
    } else {
        int dy;
        int dx;

        for (dy = 0; dy < destHeight; dy++) {
            size_t sy = ((size_t)dy * (size_t)srcHeight) / (size_t)destHeight;

            if (sy >= (size_t)srcHeight) {
                sy = (size_t)srcHeight - 1;
            }

            for (dx = 0; dx < destWidth; dx++) {
                size_t sx = ((size_t)dx * (size_t)srcWidth) / (size_t)destWidth;

                if (sx >= (size_t)srcWidth) {
                    sx = (size_t)srcWidth - 1;
                }

                img[((size_t)dy * (size_t)destWidth) + (size_t)dx] =
                    src[(sy * (size_t)srcWidth) + sx];
            }
        }
    }

    ok = 1;

cleanup:
    free(src);
    if (fp) {
        fclose(fp);
    }
    return ok;
}
